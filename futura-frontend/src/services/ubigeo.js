function actualizarProvincias() {
  const dep  = document.getElementById('nv_dpto')?.value || '';
  const selP = document.getElementById('nv_prov');
  const selD = document.getElementById('nv_dist');
  if (!selP) return;
  selP.innerHTML = '<option value="">Seleccionar provincia</option>';
  if (selD) selD.innerHTML = '<option value="">Seleccionar distrito</option>';
  if (!dep || !UBIGEO[dep]) return;
  Object.keys(UBIGEO[dep]).forEach(p => {
    selP.innerHTML += '<option value="' + p + '">' + p + '</option>';
  });
}

function actualizarDistritos() {
  const dep  = document.getElementById('nv_dpto')?.value || '';
  const prov = document.getElementById('nv_prov')?.value || '';
  const selD = document.getElementById('nv_dist');
  if (!selD) return;
  selD.innerHTML = '<option value="">Seleccionar distrito</option>';
  if (!dep || !prov || !UBIGEO[dep]?.[prov]) return;
  UBIGEO[dep][prov].forEach(d => {
    selD.innerHTML += '<option value="' + d + '">' + d + '</option>';
  });
}
